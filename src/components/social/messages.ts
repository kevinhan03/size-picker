export function useSocialMessages() {
  const { locale } = useLocaleContext();
  return locale === "en" ? en : ko;
}
export function socialError(error: unknown, c: Messages) {
  const code = error instanceof Error ? error.message : "";
  return (
    (
      {
        conflict: c.conflict,
        not_in_closet: c.notInCloset,
        invalid_upload: c.invalidUpload,
        invalid_image: c.imageError,
        upload_limit: c.uploadLimit,
        unauthorized: c.login,
        not_found: c.notFound,
        invalid_input: c.invalidInput,
        forbidden: c.forbidden,
      } as Record<string, string>
    )[code] || c.error
  );
}
